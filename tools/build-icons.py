#!/usr/bin/env python3
"""Builds assets/icons.svg, the SVG sprite that replaces the Font Awesome web
font on the public pages (index.html, card/, script.js).

It scans those files for <svg class="icon ..."><use href="/assets/icons.svg#ID">
and writes one <symbol> per ID from the Font Awesome Free SVGs.

ID rule: "name" is the solid icon, "name-regular" the regular one and
"brand-name" the brand one.

Usage (Font Awesome Free 6.5.1, the version the admin page also uses):
    npm pack @fortawesome/fontawesome-free@6.5.1 && tar xzf fortawesome-*.tgz
    python3 tools/build-icons.py package/svgs
Never edit assets/icons.svg by hand: change the markup, then run this again.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ['index.html', 'card/index.html', 'script.js']
OUT = ROOT / 'assets' / 'icons.svg'

def main(svg_dir):
    svg_dir = pathlib.Path(svg_dir)
    ids = set()
    for src in SOURCES:
        ids.update(re.findall(r'icons\.svg#([a-z0-9-]+)', (ROOT / src).read_text(encoding='utf-8')))
    symbols = []
    for icon_id in sorted(ids):
        if icon_id.startswith('brand-'):
            style, name = 'brands', icon_id[len('brand-'):]
        elif icon_id.endswith('-regular'):
            style, name = 'regular', icon_id[:-len('-regular')]
        else:
            style, name = 'solid', icon_id
        svg = (svg_dir / style / (name + '.svg')).read_text(encoding='utf-8')
        view_box = re.search(r'viewBox="([^"]+)"', svg).group(1)
        paths = ''.join(re.findall(r'<path[^>]*/>', svg))
        symbols.append(f'<symbol id="{icon_id}" viewBox="{view_box}">{paths}</symbol>')
    OUT.write_text(
        '<svg xmlns="http://www.w3.org/2000/svg">'
        '<!-- Generated by tools/build-icons.py, do not edit. Icons: Font Awesome Free 6.5.1 '
        'by @fontawesome, https://fontawesome.com, licence CC BY 4.0 (assets/fontawesome/LICENSE.txt). -->\n'
        + '\n'.join(symbols) + '\n</svg>\n', encoding='utf-8')
    print(f'{OUT.relative_to(ROOT)}: {len(symbols)} icons, {OUT.stat().st_size} bytes')

if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
